"""Retail PAL level and mission browsers.

Uses the resident level resource and authored mission tables, never a hardcoded
list of beta-only scripts. Browsing combines native hero validity with the
reference's Spider-Man/Venom story-family separation. Native force_mission
copies names and queues its own asynchronous unload.
The beta's -- REBOOT -- handler is empty (0x403F0C); its row remains a no-op.
Sibling parent menus share private storage, while children use the shared pool.
"""

NATIVE = dict(partition=0x28098C, directory=0x2CD920, resource=0x28302C,
              manager_ptr=0x699A24, applies_to_hero=0x327704,
              force_mission=0x3232F8, unload_mission=0x322AA0)
DYNAMIC_MENUS = ('dm_missions_catalog',)
MENUS = DYNAMIC_MENUS + ('dm_missions_menu', 'dm_replay_menu')
PAGE_SIZE = 64
PARENT_CAPACITY = PAGE_SIZE + 12


def emit_code(A, S, C):
    G = C['G']
    E = {k: C[k] for k in ('E_NAME', 'E_TYPE', 'E_ID', 'E_VALUE', 'E_HANDLER',
                           'E_RENDER', 'E_MIN', 'E_MAX')}

    def call(target):
        A.jal(target); A.nop()

    def check_ram(ptr, size, fail):
        A.move('a0', ptr)
        if isinstance(size, int): A.li('a1', size)
        else: A.move('a1', size)
        call('dm_catalog_ram')
        A.beqz('v0', fail); A.nop()

    def new_dyn(name, handler=None):
        A.la('a1', S(name)); A.li('a2', C['T_ACTION']); call('dm_catalog_new')
        if handler:
            A.la('t0', handler); A.sw('t0', E['E_HANDLER'], 'v0')

    def add(menu):
        A.la('a0', menu); A.move('a1', 'v0'); call('dm_add_entry')

    # Retail flags often allow Venom to run Spider-Man story/tour scripts.
    # The reference menu separates those authored families for hero types 1/2.
    # Input names have already passed the bounded native-name validation.
    A.label('dm_catalog_mission_kind')
    A.lbu('t1', 0, 'a0'); A.ori('t1', 't1', 0x20)
    A.li('t2', ord('s')); A.beq('t1', 't2', '.kind_story'); A.nop()
    A.li('t2', ord('v')); A.bne('t1', 't2', '.kind_tour'); A.nop()
    A.label('.kind_story')
    for off in (1, 2):
        A.lbu('t2', off, 'a0'); A.addiu('t2', 't2', -ord('0'))
        A.sltiu('t2', 't2', 10); A.beqz('t2', '.kind_extra'); A.nop()
    A.lbu('t2', 3, 'a0'); A.li('t3', ord('_'))
    A.bne('t2', 't3', '.kind_extra'); A.nop()
    A.li('t2', ord('s')); A.beq('t1', 't2', '.kind_spidey'); A.nop()
    A.b('.kind_venom'); A.nop()
    A.label('.kind_extra')
    A.li('t2', ord('v')); A.bne('t1', 't2', '.kind_tour'); A.nop()
    for off, ch in ((1, 'm'), (2, 'g'), (3, '_')):
        A.lbu('t2', off, 'a0')
        if ch != '_': A.ori('t2', 't2', 0x20)
        A.li('t3', ord(ch)); A.bne('t2', 't3', '.kind_tour'); A.nop()
    A.b('.kind_venom'); A.nop()
    A.label('.kind_tour'); A.move('t0', 'a0'); A.li('t5', 31)
    A.label('.kind_tour_scan')
    A.lbu('t2', 0, 't0'); A.beqz('t2', '.kind_shared'); A.nop()
    A.li('t3', ord('_')); A.bne('t2', 't3', '.kind_tour_next'); A.nop()
    A.move('t2', 't0'); A.la('t3', S('_combat_tour'))
    A.label('.kind_tour_compare')
    A.lbu('t4', 0, 't3'); A.beqz('t4', '.kind_tour_tail'); A.nop()
    A.lbu('t6', 0, 't2'); A.ori('t6', 't6', 0x20); A.ori('t4', 't4', 0x20)
    A.bne('t6', 't4', '.kind_tour_next'); A.nop()
    A.addiu('t2', 't2', 1); A.addiu('t3', 't3', 1)
    A.b('.kind_tour_compare'); A.nop()
    A.label('.kind_tour_tail')
    A.lbu('t4', 0, 't2'); A.beqz('t4', '.kind_spidey'); A.nop()
    A.addiu('t4', 't4', -ord('0')); A.sltiu('t4', 't4', 10)
    A.beqz('t4', '.kind_tour_next'); A.nop()
    A.lbu('t4', 1, 't2'); A.beqz('t4', '.kind_spidey'); A.nop()
    A.label('.kind_tour_next')
    A.addiu('t0', 't0', 1); A.addiu('t5', 't5', -1)
    A.bgtz('t5', '.kind_tour_scan'); A.nop()
    A.label('.kind_shared'); A.jr('ra'); A.move('v0', 'zero')
    A.label('.kind_spidey'); A.jr('ra'); A.li('v0', 1)
    A.label('.kind_venom'); A.jr('ra'); A.li('v0', 2)

    f = A.func('dm_catalog_mission_applies', saves=['s0'])
    A.move('s0', 'a0'); call(NATIVE['applies_to_hero'])
    A.beqz('v0', f.epi); A.nop()
    A.lw('a0', 0x18, 's0'); call('dm_catalog_mission_kind')
    A.beqz('v0', '.mission_applies_yes'); A.nop()
    A.lw_abs('t0', 'dm_catalog_hero_type')
    A.addiu('t1', 't0', -1); A.sltiu('t1', 't1', 2)
    A.beqz('t1', '.mission_applies_yes'); A.nop()
    A.xor('v0', 'v0', 't0'); A.sltiu('v0', 'v0', 1); f.ret()
    A.label('.mission_applies_yes'); A.li('v0', 1); f.end()

    # Sort mode 3: keep district submenus in loaded order, Unload first,
    # alphabetized mission rows, then stable pagination controls.
    f = A.func('dm_catalog_mission_rank', saves=['s0'])
    A.move('s0', 'a0')
    for text, rank in (('UNLOAD CURRENT MISSION', 0), ('Previous page', 2), ('Next page', 2)):
        nxt = A.newlabel('mission_rank')
        A.move('a0', 's0'); A.la('a1', S(text)); call(G['strcasecmp'])
        A.bnez('v0', nxt); A.nop()
        A.li('v0', rank); f.ret(); A.label(nxt)
    A.li('v0', 1); f.end()
    f = A.func('dm_catalog_mission_compare', saves=['s0', 's1', 's2'])
    A.move('s0', 'a0'); A.move('s1', 'a1'); call('dm_catalog_mission_rank')
    A.move('s2', 'v0'); A.move('a0', 's1'); call('dm_catalog_mission_rank')
    A.subu('v0', 's2', 'v0'); A.bnez('v0', f.epi); A.nop()
    A.li('t0', 2); A.beq('s2', 't0', f.epi); A.nop()
    A.move('a0', 's0'); A.move('a1', 's1'); call(G['strcasecmp']); f.end()

    # Validate complete ranges in the 32 MiB EE RAM. a0=base, a1=size.
    A.label('dm_catalog_ram')
    A.li('t0', C['BASE']); A.sltu('t0', 'a0', 't0')
    A.bnez('t0', '.cat_ram_bad'); A.move('v0', 'zero')
    A.addu('t1', 'a0', 'a1'); A.sltu('t0', 't1', 'a0')
    A.bnez('t0', '.cat_ram_bad'); A.nop()
    A.li('t0', 0x02000001); A.sltu('v0', 't1', 't0')
    A.label('.cat_ram_bad'); A.jr('ra'); A.nop()

    # Runtime resource names must terminate within their 32-byte native fields.
    f = A.func('dm_catalog_name', saves=['s0'])
    A.move('s0', 'a0'); A.li('a1', 32); call('dm_catalog_ram')
    A.beqz('v0', f.epi); A.nop()
    A.move('t0', 'zero'); A.move('v0', 'zero')
    A.label('.cat_name_loop')
    A.addu('t1', 's0', 't0'); A.lbu('t2', 0, 't1')
    A.beqz('t2', '.cat_name_end'); A.nop()
    A.addiu('t0', 't0', 1); A.sltiu('t3', 't0', 32)
    A.bnez('t3', '.cat_name_loop'); A.nop()
    f.ret()
    A.label('.cat_name_end'); A.sltu('v0', 'zero', 't0')
    f.end()

    # Own every visible name: district packs may stream while focus is released.
    A.label('dm_catalog_copy32')
    A.move('t0', 'zero'); A.beqz('a1', '.cat_copy_end'); A.nop()
    A.label('.cat_copy_loop')
    A.addu('t1', 'a1', 't0'); A.lbu('t2', 0, 't1')
    A.addu('t1', 'a0', 't0'); A.sb('t2', 0, 't1')
    A.beqz('t2', '.cat_copy_done'); A.nop()
    A.addiu('t0', 't0', 1); A.sltiu('t3', 't0', 31)
    A.bnez('t3', '.cat_copy_loop'); A.nop()
    A.label('.cat_copy_end'); A.addu('t1', 'a0', 't0'); A.sb('zero', 0, 't1')
    A.label('.cat_copy_done'); A.jr('ra'); A.nop()

    # a0=name. Pack keys changed from beta type 0x18 to retail type 0x19.
    f = A.func('dm_catalog_has_pack', locals_size=16)
    A.move('a2', 'a0'); A.move('a0', 'sp'); A.move('a1', 'zero')
    A.move('a3', 'zero'); call(G['string_hash_init'])
    A.li('t0', 0x19); A.sw('t0', 4, 'sp')
    A.move('a0', 'sp'); A.move('a1', 'zero'); A.move('a2', 'zero')
    A.move('a3', 'zero'); call(G['get_pack_file_stats'])
    f.end()

    # Private parent storage is shared only by sibling roots. Hero/district
    # children use the normal dynamic pool, leaving parent entries/names intact.
    A.label('dm_catalog_new')
    A.lw_abs('a0', 'dm_catalog_pool'); A.j('dm_alloc'); A.nop()

    f = A.func('dm_catalog_parent', saves=['s0', 's1', 's2'])
    A.move('s0', 'a0'); A.move('s1', 'a1')
    A.lw_abs('s2', 'dm_active_menu'); A.bne('s2', 's1', '.catalog_parent_found'); A.nop()
    A.lw('s2', C['M_PARENT'], 's1')
    A.label('.catalog_parent_found')
    A.sw_abs('s1', 'dm_catalog_target')
    A.la('t0', 'dm_catalog_parent_pool_desc'); A.sw('zero', 4, 't0')
    A.sw_abs('t0', 'dm_catalog_pool')
    A.la('t0', 'dm_catalog_parent_names'); A.sw_abs('t0', 'dm_catalog_name_base')
    A.sw_abs('zero', 'dm_catalog_used'); A.sw_abs('zero', 'dm_catalog_more')
    A.move('a0', 's1'); A.move('a1', 'a2'); A.move('a2', 'zero'); call('dm_menu_reset')
    A.sw('s1', C['E_SUBMENU'], 's0')
    A.sw('s2', C['M_PARENT'], 's1')
    f.end()

    f = A.func('p_levels_catalog', saves=['s0', 's1', 's2'], locals_size=16)
    A.sw_abs('a0', 'dm_levels_entry')
    A.la('a1', 'dm_level_menu'); A.la('a2', S('Level Select')); call('dm_catalog_parent')
    A.la('a1', S('Hero Select')); A.li('a2', C['T_SUB']); call('dm_catalog_new')
    A.la('t0', 'p_hero'); A.sw('t0', C['E_POPULATE'], 'v0'); add('dm_level_menu')
    A.lw_abs('t0', 'dm_level_page'); A.sll('t1', 't0', 6); A.sw('t1', 12, 'sp')
    A.move('a0', 'zero'); call(NATIVE['partition'])
    A.move('s0', 'v0'); check_ram('s0', 12, '.levels_finish')
    A.lw('s0', 8, 's0'); check_ram('s0', 4, '.levels_finish')
    A.lw('s0', 0, 's0'); check_ram('s0', 4, '.levels_finish')
    A.move('a0', 's0'); call(NATIVE['directory'])
    A.move('s0', 'v0'); check_ram('s0', 4, '.levels_finish')
    A.move('a0', 'sp'); A.move('a1', 'zero'); A.la('a2', S('level'))
    A.move('a3', 'zero'); call(G['string_hash_init'])
    A.li('t0', 9); A.sw('t0', 4, 'sp'); A.sw('zero', 8, 'sp')
    A.move('a0', 's0'); A.move('a1', 'sp'); A.addiu('a2', 'sp', 8)
    A.move('a3', 'zero'); call(NATIVE['resource'])
    A.move('s0', 'v0'); A.lw('s1', 8, 'sp')
    A.li('t0', 0x90000); A.sltu('t0', 't0', 's1')
    A.bnez('t0', '.levels_finish'); A.nop()
    check_ram('s0', 's1', '.levels_finish')
    A.label('.levels_loop')
    A.sltiu('t0', 's1', 0x90); A.bnez('t0', '.levels_finish'); A.nop()
    A.move('a0', 's0'); call('dm_catalog_name')
    A.beqz('v0', '.levels_next'); A.nop()
    A.move('a0', 's0'); call('dm_catalog_has_pack')
    A.beqz('v0', '.levels_next'); A.nop()
    A.lw('t0', 12, 'sp'); A.beqz('t0', '.levels_add'); A.nop()
    A.addiu('t0', 't0', -1); A.sw('t0', 12, 'sp')
    A.b('.levels_next'); A.nop()
    A.label('.levels_add')
    A.lw_abs('t0', 'dm_catalog_used')
    A.sltiu('t0', 't0', PAGE_SIZE); A.beqz('t0', '.levels_full'); A.nop()
    A.move('a1', 's0'); A.li('a2', C['T_ACTION']); call('dm_catalog_new')
    A.beqz('v0', f.epi); A.nop()
    A.move('s2', 'v0')
    A.lw_abs('t0', 'dm_catalog_used'); A.sll('t0', 't0', 6)
    A.la('a0', 'dm_catalog_parent_names'); A.addu('a0', 'a0', 't0')
    A.sw('a0', E['E_NAME'], 's2'); A.sw('a0', E['E_ID'], 's2')
    A.move('a1', 's0'); call('dm_catalog_copy32')
    A.la('t0', 'h_catalog_level'); A.sw('t0', E['E_HANDLER'], 's2')
    # Display the requested label while retaining the owned native launch key.
    A.move('a0', 's0'); A.la('a1', S('CITY_ARENA')); call(G['strcasecmp'])
    A.bnez('v0', '.levels_native_name'); A.nop()
    A.la('t0', S('city')); A.sw('t0', E['E_NAME'], 's2')
    A.la('t0', 'h_city_restart'); A.sw('t0', E['E_HANDLER'], 's2')
    A.la('t0', 'r_city_restart_status'); A.sw('t0', E['E_RENDER'], 's2')
    A.label('.levels_native_name')
    A.move('v0', 's2'); add('dm_level_menu')
    A.lw_abs('t0', 'dm_catalog_used'); A.addiu('t0', 't0', 1); A.sw_abs('t0', 'dm_catalog_used')
    A.label('.levels_next'); A.addiu('s0', 's0', 0x90)
    A.b('.levels_loop'); A.addiu('s1', 's1', -0x90)
    A.label('.levels_full'); A.li('t0', 1); A.sw_abs('t0', 'dm_catalog_more')
    A.label('.levels_finish')
    # Both the beta PS2 and supplied prerelease source have an empty handler.
    new_dyn('-- REBOOT --'); add('dm_level_menu')
    A.li('a0', 0); call('dm_catalog_page_entries')
    f.end()

    f = A.func('h_catalog_level', saves=['s0', 's1'], locals_size=16)
    A.lw('s1', E['E_ID'], 'a0')
    A.lw_abs('s0', G['g_game_ptr']); A.beqz('s0', f.epi); A.nop()
    A.move('a0', 's1'); call('dm_catalog_name')
    A.beqz('v0', f.epi); A.nop()
    A.move('a0', 's1'); call('dm_catalog_has_pack')
    A.beqz('v0', f.epi); A.nop()
    A.move('a0', 'sp'); A.move('a1', 's1'); call(G['mstring_ctor'])
    call('dm_hide')
    A.move('a0', 's0'); A.move('a1', 'sp'); A.move('a2', 'zero')
    call(G['load_new_level'])
    A.sw_abs('zero', 'dm_replay_valid')
    A.move('a0', 'sp'); A.move('a1', 'zero'); call(G['mstring_finalize'])
    A.move('a0', 'sp'); A.move('a1', 'zero'); call(G['mcontainer_finalize'])
    f.end()

    # Current hero type, null-safe (the native condition filter assumes these).
    A.label('dm_catalog_hero')
    A.move('v0', 'zero'); A.lw_abs('t0', G['g_world_ptr'])
    A.beqz('t0', '.cat_hero_end'); A.nop()
    A.lw('t0', C['WORLD_HERO0'], 't0')
    A.beqz('t0', '.cat_hero_end'); A.nop()
    A.lw('t0', C['ACTOR_CONTROLLER'], 't0')
    A.beqz('t0', '.cat_hero_end'); A.nop()
    A.lw('v0', C['CONTROLLER_HERO_TYPE'], 't0')
    A.label('.cat_hero_end'); A.jr('ra'); A.nop()

    f = A.func('dm_catalog_capture_scene')
    A.la('a0', 'dm_catalog_scene'); A.li('a1', 33); A.la('a2', S('%s'))
    A.li('a3', G['scene_name']); call(G['snprintf'])
    call('dm_catalog_hero'); A.sw_abs('v0', 'dm_catalog_hero_type')
    f.end()

    f = A.func('p_missions_catalog', saves=['s0', 's1', 's2', 's3'])
    A.sw_abs('a0', 'dm_missions_entry')
    A.la('a1', 'dm_missions_menu'); A.la('a2', S('Missions')); call('dm_catalog_parent')
    A.li('t0', 3); A.sw_abs('t0', 'dm_missions_menu', C['M_SORT'])
    call('dm_catalog_hero'); A.lw_abs('t0', 'dm_catalog_hero_type')
    A.bne('v0', 't0', '.missions_reset_page'); A.nop()
    A.la('a0', 'dm_catalog_scene'); A.li('a1', G['scene_name']); call(G['strcasecmp'])
    A.beqz('v0', '.missions_page_ready'); A.nop()
    A.label('.missions_reset_page'); A.sw_abs('zero', 'dm_mission_page')
    A.label('.missions_page_ready')
    call('dm_catalog_capture_scene')
    A.sw_abs('zero', 'dm_district_page')
    A.li('t0', -1); A.sw_abs('t0', 'dm_catalog_district_index')
    new_dyn('UNLOAD CURRENT MISSION', 'h_catalog_unload'); add('dm_missions_menu')
    A.lw_abs('t0', 'dm_mission_page'); A.sll('t0', 't0', 6); A.sw_abs('t0', 'dm_mission_skip')
    A.lw_abs('s0', NATIVE['manager_ptr']); check_ram('s0', 0x100, '.missions_finish')
    A.lw('s2', 0x38, 's0'); A.sltiu('t0', 's2', 9)
    A.beqz('t0', '.missions_finish'); A.move('s1', 'zero')
    A.label('.missions_groups')
    A.sltu('t0', 's1', 's2'); A.beqz('t0', '.missions_globals'); A.nop()
    A.sll('t0', 's1', 2); A.addu('t0', 't0', 's0'); A.lw('s3', 0x18, 't0')
    check_ram('s3', 0x48, '.missions_next_group')
    A.lw('s3', 0x44, 's3'); check_ram('s3', 0xC4, '.missions_next_group')
    A.lw('s3', C['REGION_MASH'], 's3'); A.move('a0', 's3'); call('dm_catalog_name')
    A.beqz('v0', '.missions_next_group'); A.nop()
    A.move('a1', 's3'); A.li('a2', C['T_SUB']); call('dm_catalog_new')
    A.beqz('v0', '.missions_globals'); A.nop()
    A.sw('s1', C['E_ID'], 'v0'); A.sw_abs('v0', 'dm_catalog_pending_entry')
    A.la('t0', 'p_mission_district'); A.sw('t0', C['E_POPULATE'], 'v0')
    A.sll('t0', 's1', 5); A.la('a0', 'dm_catalog_district_names'); A.addu('a0', 'a0', 't0')
    A.sw('a0', C['E_NAME'], 'v0'); A.move('a1', 's3'); call('dm_catalog_copy32')
    A.lw_abs('v0', 'dm_catalog_pending_entry'); add('dm_missions_menu')
    A.label('.missions_next_group'); A.b('.missions_groups'); A.addiu('s1', 's1', 1)
    A.label('.missions_globals')
    A.lw_abs('t0', 'dm_catalog_hero_type'); A.beqz('t0', '.missions_finish'); A.nop()
    A.lw('a0', 0x14, 's0'); A.move('a1', 'zero'); call('dm_catalog_append_table')
    A.sw_abs('v0', 'dm_catalog_more')
    A.label('.missions_finish'); A.li('a0', 1); call('dm_catalog_page_entries')
    f.end()

    f = A.func('p_mission_district', saves=['s0', 's1', 's2'])
    A.sw_abs('a0', 'dm_district_entry'); A.lw('s1', C['E_ID'], 'a0')
    A.lw_abs('t0', 'dm_catalog_district_index')
    A.beq('s1', 't0', '.district_page_ready'); A.nop()
    A.sw_abs('zero', 'dm_district_page')
    A.label('.district_page_ready')
    A.sw_abs('s1', 'dm_catalog_district_index')
    A.la('a1', 'dm_missions_catalog'); A.lw('a2', C['E_NAME'], 'a0')
    A.move('a3', 'zero'); call('dm_dyn_menu')
    A.li('t0', 3); A.sw_abs('t0', 'dm_missions_catalog', C['M_SORT'])
    A.la('t0', 'dm_missions_catalog'); A.sw_abs('t0', 'dm_catalog_target')
    A.la('t0', 'dm_missions_menu'); A.sw_abs('t0', 'dm_missions_catalog', C['M_PARENT'])
    A.la('t0', 'dm_dyn_pool_desc'); A.sw_abs('t0', 'dm_catalog_pool')
    A.la('t0', 'dm_catalog_names'); A.sw_abs('t0', 'dm_catalog_name_base')
    A.sw_abs('zero', 'dm_catalog_used'); A.sw_abs('zero', 'dm_catalog_more')
    A.lw_abs('t0', 'dm_district_page'); A.sll('t0', 't0', 6); A.sw_abs('t0', 'dm_mission_skip')
    A.la('a0', 'dm_catalog_scene'); A.li('a1', G['scene_name']); call(G['strcasecmp'])
    A.bnez('v0', '.district_finish'); A.nop()
    call('dm_catalog_hero'); A.lw_abs('t0', 'dm_catalog_hero_type')
    A.bne('v0', 't0', '.district_finish'); A.nop()
    A.lw_abs('s0', NATIVE['manager_ptr']); check_ram('s0', 0x100, '.district_finish')
    A.lw('t0', 0x38, 's0'); A.sltiu('t1', 't0', 9)
    A.beqz('t1', '.district_finish'); A.nop()
    A.sltu('t0', 's1', 't0'); A.beqz('t0', '.district_finish'); A.nop()
    A.sll('t0', 's1', 2); A.addu('t0', 's0', 't0'); A.lw('s2', 0x18, 't0')
    check_ram('s2', 0x48, '.district_finish')
    A.lw('s0', 0x44, 's2'); check_ram('s0', 0xC4, '.district_finish')

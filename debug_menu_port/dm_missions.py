def emit_menus(A, S, C):
    def call(target): A.jal(target); A.nop()
    def sub(parent, title, menu=None, populate=None):
        A.la('a0', parent)
        if menu: A.la('a1', menu)
        else: A.move('a1', 'zero')
        A.la('a2', S(title))
        if populate: A.la('a3', populate)
        else: A.move('a3', 'zero')
        call('dm_add_sub')
    def action(menu, title, handler, render=None):
        A.la('a1', S(title)); A.li('a2', C['T_ACTION']); call('dm_new')
        A.la('t0', handler); A.sw('t0', C['E_HANDLER'], 'v0')
        if render: A.la('t0', render); A.sw('t0', C['E_RENDER'], 'v0')
        A.la('a0', menu); A.move('a1', 'v0'); call('dm_add_entry')
    # The parent builder attaches p_levels_catalog to its Level Select root.
    sub('dm_root_menu', 'Missions', populate='p_missions_catalog')
    A.la('a0', 'dm_replay_menu'); A.la('a1', S('Replay')); A.move('a2', 'zero'); call('dm_menu_reset')
    sub('dm_root_menu', 'Replay', 'dm_replay_menu')
    action('dm_replay_menu', 'Start', 'h_replay_last')




    # Explicit reference orders are independent of module construction order.
    for kind in ('root', 'game'):
        f = A.func('dm_%s_rank' % kind, saves=['s0', 's1', 's2'])
        A.move('s0', 'a0')
        A.la('s1', 'tbl_%s_order' % kind)
        A.move('s2', 'zero')
        A.label('.%s_rank_loop' % kind)
        A.lw('a1', 0, 's1')

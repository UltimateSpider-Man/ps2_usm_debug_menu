    A.beq('t0', 't1', '.set_byte')
    A.addiu('t1', 'zero', T_BYTEINTP)
    A.beq('t0', 't1', '.set_byte')
    A.nop()
    A.jr('ra')
    A.sw('a1', E_VALUE, 'a0')
    A.label('.set_ptr')
    A.lw('t2', E_VALUE, 'a0')
    A.beqz('t2', '.set_done')
    A.nop()

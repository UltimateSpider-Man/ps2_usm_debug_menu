    A.addiu('t1', 'zero', T_BOOLP)
    A.beq('t0', 't1', '.set_ptr')
    A.addiu('t1', 'zero', T_INTP)
    A.beq('t0', 't1', '.set_ptr')
    A.addiu('t1', 'zero', T_FLOATP)

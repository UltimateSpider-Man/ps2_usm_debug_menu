    A.move('s1', 'a1')
    A.beqz('s1', f.epi)
    A.nop()
    A.lw('t0', M_COUNT, 's0')
    A.addiu('t0', 't0', 1)
    A.sw('t0', M_COUNT, 's0')
    A.lw('s3', M_FIRST, 's0')            # cur
    A.bnez('s3', '.ae_nonempty')
    A.move('s2', 'zero')                 # prev
    A.sw('s1', M_FIRST, 's0')
    A.sw('s1', M_LAST, 's0')
    A.sw('zero', E_PREV, 's1')
    f.ret()
    A.label('.ae_nonempty')
    A.lw('t0', E_TYPE, 's1')
    A.addiu('t1', 'zero', T_SUB)
    A.xor('s4', 't0', 't1')
    A.sltiu('s4', 's4', 1)               # s4 = is_sub
    A.lw('s5', M_SORT, 's0')
    A.li('t0', 4); A.beq('s5', 't0', '.ae_game_loop'); A.nop()
    # phase 1: walk leading submenu entries
    A.label('.ae_loop1')
    A.beqz('s3', '.ae_insert')
    A.nop()
    A.lw('t0', E_TYPE, 's3')
    A.addiu('t1', 'zero', T_SUB)
    A.bne('t0', 't1', '.ae_phase2')
    A.nop()
    A.beqz('s4', '.ae_adv1')             # new entry not a submenu -> skip all submenus
    A.nop()
    A.beqz('s5', '.ae_adv1')
    A.nop()
    A.li('t0', 3); A.beq('s5', 't0', '.ae_adv1'); A.nop()
    A.lw('a0', E_NAME, 's3')
    A.lw('a1', E_NAME, 's1')
    A.addiu('t0', 'zero', 2)
    A.bne('s5', 't0', '.ae_alpha1')
    A.nop()
    call('dm_root_compare')
    A.b('.ae_compare1')
    A.nop()
    A.label('.ae_alpha1')
    call(G['strcasecmp'])
    A.label('.ae_compare1')
    A.bgtz('v0', '.ae_insert')
    A.nop()
    A.label('.ae_adv1')
    A.move('s2', 's3')
    A.b('.ae_loop1')
    A.lw('s3', E_NEXT, 's3')
    A.label('.ae_phase2')
    A.bnez('s4', '.ae_insert')           # submenu goes right after the submenu block
    A.nop()
    A.label('.ae_loop2')
    A.beqz('s3', '.ae_insert')
    A.nop()
    A.beqz('s5', '.ae_adv2')
    A.nop()
    A.lw('a0', E_NAME, 's3')
    A.lw('a1', E_NAME, 's1')
    A.li('t0', 3); A.bne('s5', 't0', '.ae_alpha2'); A.nop()
    call('dm_catalog_mission_compare')
    A.b('.ae_compare2'); A.nop()
    A.label('.ae_alpha2')
    call(G['strcasecmp'])
    A.label('.ae_compare2')
    A.bgtz('v0', '.ae_insert')
    A.nop()
    A.label('.ae_adv2')
    A.move('s2', 's3')
    A.b('.ae_loop2')
    A.lw('s3', E_NEXT, 's3')
    # Game follows the video's complete order, including its three submenus.
    A.label('.ae_game_loop')
    A.beqz('s3', '.ae_insert'); A.nop()
    A.lw('a0', E_NAME, 's3'); A.lw('a1', E_NAME, 's1')
    call('dm_game_compare')
    A.bgtz('v0', '.ae_insert'); A.nop()
    A.move('s2', 's3')
    A.b('.ae_game_loop'); A.lw('s3', E_NEXT, 's3')
    A.label('.ae_insert')
    A.sw('s2', E_PREV, 's1')
    A.sw('s3', E_NEXT, 's1')
    A.beqz('s2', '.ae_nofirst')
    A.nop()
    A.b('.ae_link2')
    A.sw('s1', E_NEXT, 's2')
    A.label('.ae_nofirst')
    A.sw('s1', M_FIRST, 's0')
    A.label('.ae_link2')
    A.beqz('s3', '.ae_nolast')
    A.nop()
    A.b(f.epi)
    A.sw('s1', E_PREV, 's3')
    A.label('.ae_nolast')
    A.sw('s1', M_LAST, 's0')
    f.end()

    # dm_add_sub(a0=parent, a1=submenu or 0, a2=name, a3=populate) -> v0 entry
    f = A.func('dm_add_sub', saves=['s0', 's1', 's2', 's3'])
    A.move('s0', 'a0')
    A.move('s1', 'a1')
    A.move('s3', 'a3')
    A.move('a1', 'a2')
    A.addiu('a2', 'zero', T_SUB)
    A.jal('dm_new')
    A.nop()
    A.beqz('v0', f.epi)
    A.nop()
    A.sw('s1', E_SUBMENU, 'v0')
    A.sw('s3', E_POPULATE, 'v0')
    A.move('s2', 'v0')
    A.move('a0', 's0')
    A.jal('dm_add_entry')
    A.move('a1', 's2')
    A.move('v0', 's2')

def build():
    A = Asm(BASE)
    strings = {}

    def S(text):
        """label of a rodata string (emitted later)."""
        if text not in strings:
            strings[text] = '.str%d' % len(strings)
        return strings[text]

    def call(target):
        A.jal(target)
        A.nop()

    def ld_global(r, addr):          # r = *(u32*)addr
        A.lw_abs(r, addr)

    # ================================================================ hooks
    # app::tick: replaces "jal link_system::frame_advance" (delay slot sets $f12 = dt)
    A.label('hook_tick')
    A.addiu('sp', 'sp', -0x30)
    A.sd('ra', 0, 'sp')
    A.sd('a0', 8, 'sp')
    A.sd('a1', 0x10, 'sp')
    A.swc1('f12', 0x18, 'sp')
    call('dm_entities_guard')
    call('dm_ai_validate')
    A.lwc1('f12', 0x18, 'sp')
    call('dm_frame_advance')
    call('dm_hero_tick')
    call('dm_game_actions_tick')
    A.ld('ra', 0, 'sp')
    A.ld('a0', 8, 'sp')
    A.ld('a1', 0x10, 'sp')
    A.lwc1('f12', 0x18, 'sp')
    A.j(G['link_system_frame_advance'])
    A.addiu('sp', 'sp', 0x30)

    # game::render_ui: replaces the "jal nglListEndScene" that closes the UI scene
    A.label('hook_render')
    A.addiu('sp', 'sp', -0x10)
    A.sd('ra', 0, 'sp')
    call('dm_entities_guard')
    call('dm_ai_validate')
    call('dm_render')
    A.ld('ra', 0, 'sp')
    A.j(G['nglListEndScene'])
    A.addiu('sp', 'sp', 0x10)

    # IGOFrontEnd::CheckPauseUnpause: GAME_PAUSE read is ignored while the menu used input
    # this frame (beta checked debug_menu::had_menu_this_frame here)
    A.label('hook_pause')
    A.lw_abs('t0', 'dm_had_menu_this_frame')
    A.bnez('t0', '.hp_block')
    A.nop()
    A.j(G['get_control_delta'])
    A.nop()
    A.label('.hp_block')
    A.mtc1('zero', 'f0')
    A.jr('ra')
    A.nop()

    # IGOZoomOutMap::UpdateSelectButton -> OnSelectPress: skipped while menu is up
    # (beta OnSelectPress returned early on active_menu / had_menu_this_frame)
    A.label('hook_map')
    A.lw_abs('t0', 'dm_active_menu')
    A.lw_abs('t1', 'dm_had_menu_this_frame')
    A.or_('t0', 't0', 't1')
    A.bnez('t0', '.hm_skip')
    A.nop()
    A.j(G['igo_zoom_map_on_select'])
    A.nop()
    A.label('.hm_skip')
    A.jr('ra')
    A.nop()

    # ================================================================ pools / menus
    # dm_alloc(a0 = pool descriptor {base, used, cap}, a1 = name, a2 = type) -> v0 entry or 0
    A.label('dm_alloc')
    A.lw('t0', 4, 'a0')
    A.lw('t1', 8, 'a0')
    A.slt('t2', 't0', 't1')
    A.beqz('t2', '.alloc_fail')
    A.lw('t3', 0, 'a0')
    A.sll('t4', 't0', 5)             # used * 48 = used*32 + used*16
    A.sll('t5', 't0', 4)
    A.addu('t4', 't4', 't5')
    A.addu('v0', 't3', 't4')
    A.addiu('t0', 't0', 1)
    A.sw('t0', 4, 'a0')
    for off in range(0, E_SIZE, 4):
        A.sw('zero', off, 'v0')
    A.sw('a1', E_NAME, 'v0')
    A.sw('a2', E_TYPE, 'v0')
    A.addiu('t6', 'zero', 1)
    A.jr('ra')
    A.sw('t6', E_MAX, 'v0')
    A.label('.alloc_fail')
    A.jr('ra')
    A.move('v0', 'zero')

    # dm_new(a1=name, a2=type) static pool ; dm_new_dyn(...) dynamic pool
    A.label('dm_new')
    A.la('a0', 'dm_static_pool_desc')
    A.b('dm_alloc')
    A.nop()
    A.label('dm_new_dyn')
    A.la('a0', 'dm_dyn_pool_desc')
    A.b('dm_alloc')
    A.nop()

    # dm_menu_reset(a0=menu, a1=title, a2=sort)
    A.label('dm_menu_reset')
    A.sw('a1', M_TITLE, 'a0')
    A.sw('zero', M_FIRST, 'a0')
    A.sw('zero', M_LAST, 'a0')
    A.sw('zero', M_HIGHLIGHT, 'a0')

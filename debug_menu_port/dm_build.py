        A.beqz('v0', '.%s_rank_found' % kind)
        A.addiu('s1', 's1', 4)
        A.b('.%s_rank_loop' % kind)
        A.addiu('s2', 's2', 1)
        A.label('.%s_rank_found' % kind)
        A.move('v0', 's2')
        f.end()
        f = A.func('dm_%s_compare' % kind, saves=['s0', 's1'])
        A.move('s0', 'a1')
        call('dm_%s_rank' % kind)
        A.move('s1', 'v0')
        A.move('a0', 's0')
        call('dm_%s_rank' % kind)
        A.subu('v0', 's1', 'v0')

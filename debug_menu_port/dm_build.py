    # ================================================================ values
    # dm_get(a0=entry) -> v0
    A.label('dm_get')
    A.lw('t0', E_TYPE, 'a0')
    A.lw('v0', E_VALUE, 'a0')
    A.addiu('t1', 'zero', T_BOOLP)
    A.beq('t0', 't1', '.get_ptr')
    A.addiu('t1', 'zero', T_INTP)
    A.beq('t0', 't1', '.get_ptr')
    A.addiu('t1', 'zero', T_FLOATP)
    A.beq('t0', 't1', '.get_ptr')
    A.addiu('t1', 'zero', T_BYTEP)
    A.beq('t0', 't1', '.get_byte')
    A.addiu('t1', 'zero', T_BYTEINTP)
    A.beq('t0', 't1', '.get_byte')
    A.nop()
    A.jr('ra')
    A.nop()
    A.label('.get_ptr')
    A.beqz('v0', '.get_null')
    A.nop()
    A.jr('ra')
    A.lw('v0', 0, 'v0')
    A.label('.get_byte')
    A.beqz('v0', '.get_null')
    A.nop()
    A.jr('ra')
    A.lbu('v0', 0, 'v0')
    A.label('.get_null')
    A.jr('ra')
    A.move('v0', 'zero')

    # dm_set(a0=entry, a1=value)

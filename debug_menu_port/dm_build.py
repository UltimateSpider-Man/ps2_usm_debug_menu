    A.beq('t0', 't1', '.oc_bool')
    A.addiu('t1', 'zero', T_BOOLP)
    A.beq('t0', 't1', '.oc_bool')
    A.addiu('t1', 'zero', T_BYTEP)
    A.beq('t0', 't1', '.oc_bool')
    A.addiu('t1', 'zero', T_BYTEINTP)
    A.beq('t0', 't1', '.oc_int')
    A.addiu('t1', 'zero', T_INT)
    A.beq('t0', 't1', '.oc_int')
    A.addiu('t1', 'zero', T_INTP)
    A.beq('t0', 't1', '.oc_int')

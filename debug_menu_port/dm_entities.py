"""Retail entity variants and typed Chuck global-variable browsers.

Verified against SLES_536.72. Entity membership comes from world+0x74's
multi_vector (constructor 0x26F1A8); variant access uses the same virtual calls
as 0x54E5E4. Script type metadata uses the retail container lookup 0x2F04BC.
The variant child has its own pool so the entity parent survives navigation.
"""
from types import SimpleNamespace
from asm5900 import Ref

DYNAMIC_MENUS = ('dm_entities_menu', 'dm_variant_menu', 'dm_script_vars')
MENUS = DYNAMIC_MENUS + ('dm_script_menu',)
PAGE_SIZE = 64
NAME_SIZE = 48
VARIANT_POOL_SIZE = PAGE_SIZE + 2
HASH_TEXT = 0x27E8C0
APPLY_VARIANT = 0x20C370
SCRIPT_LOOKUP = 0x2F04BC
GAME_VARS, SHARED_VARS = 0x683418, 0x68341C


def emit_code(A, S, C):
    D = SimpleNamespace(**C)
    G = C['G']

    def call(addr):
        A.jal(addr); A.nop()

    def valid_ptr(reg, failure, aligned=True):
        A.li('t6', 0x100000)
        A.sltu('t7', reg, 't6')
        A.bnez('t7', failure); A.nop()
        A.li('t6', 0x02000000)
        A.sltu('t7', reg, 't6')
        A.beqz('t7', failure); A.nop()
        if aligned:
            A.andi('t7', reg, 3)
            A.bnez('t7', failure); A.nop()

    def page_action(menu, title, handler):
        A.la('a1', S(title))
        A.li('a2', D.T_ACTION)
        if menu == 'dm_variant_menu':
            A.la('a0', 'dm_variant_pool_desc'); call('dm_alloc')
        else:
            call('dm_new_dyn')
        skip = A.newlabel('page_alloc_fail')
        A.beqz('v0', skip); A.nop()
        A.la('t0', handler); A.sw('t0', D.E_HANDLER, 'v0')
        A.la('a0', menu); A.move('a1', 'v0'); call('dm_add_entry')
        A.label(skip)

    # a0=destination, a1=source; copy at most NAME_SIZE-1 characters.
    f = A.func('dm_copy_entity_name')
    A.li('t0', NAME_SIZE - 1)
    A.label('.ecn_copy')
    A.lbu('t1', 0, 'a1'); A.sb('t1', 0, 'a0')
    A.beqz('t1', f.epi); A.nop()
    A.addiu('a0', 'a0', 1); A.addiu('a1', 'a1', 1)
    A.addiu('t0', 't0', -1)
    A.bnez('t0', '.ecn_copy'); A.nop()
    A.sb('zero', 0, 'a0')
    f.end()

    # a0=entity -> v0=variant interface or zero. Do not call the extended
    # conglomerate vtable on an ordinary entity.
    f = A.func('dm_entity_variant_ifc', saves=['s0'])
    A.move('s0', 'a0'); valid_ptr('s0', '.evi_none')
    A.lw('t0', 4, 's0'); A.andi('t0', 't0', 4)
    A.beqz('t0', '.evi_none'); A.nop()
    A.lw('t0', 0, 's0'); valid_ptr('t0', '.evi_none')
    A.lw('t9', 0x544, 't0'); valid_ptr('t9', '.evi_none')
    A.lh('a0', 0x540, 't0'); A.addu('a0', 'a0', 's0')
    A.jalr('t9'); A.nop()
    A.beqz('v0', '.evi_none'); A.nop()
    A.lw('t0', 0, 's0'); A.lw('t9', 0x54C, 't0')
    valid_ptr('t9', '.evi_none')
    A.lh('a0', 0x548, 't0'); A.addu('a0', 'a0', 's0')
    A.jalr('t9'); A.nop()
    valid_ptr('v0', '.evi_none')
    f.ret()
    A.label('.evi_none'); A.move('v0', 'zero')
    f.end()

    # Walk the live multi_vector rather than dereferencing a possibly removed
    # entry. All walks are bounded; comparison itself does not touch the entity.
    f = A.func('dm_entity_is_loaded')
    valid_ptr('a0', '.eil_no')
    A.lw_abs('t0', G['g_world_ptr']); valid_ptr('t0', '.eil_no')
    A.lw('t1', D.WORLD_HERO0, 't0')
    A.beq('a0', 't1', '.eil_yes'); A.nop()
    A.lw('t0', 0x78, 't0'); valid_ptr('t0', '.eil_no')
    A.lw('t1', 0, 't0'); A.li('t5', 16384)
    A.label('.eil_node')
    A.beq('t1', 't0', '.eil_no'); A.nop()
    valid_ptr('t1', '.eil_no')
    A.lw('t2', 8, 't1'); A.lw('t3', 12, 't1')
    A.label('.eil_vector')
    A.beq('t2', 't3', '.eil_next_node'); A.nop()
    A.sltu('t4', 't2', 't3'); A.beqz('t4', '.eil_no'); A.nop()
    valid_ptr('t2', '.eil_no')
    A.lw('t4', 0, 't2'); A.beq('t4', 'a0', '.eil_yes'); A.nop()
    A.addiu('t2', 't2', 4); A.addiu('t5', 't5', -1)
    A.bgtz('t5', '.eil_vector'); A.nop()
    A.b('.eil_no'); A.nop()
    A.label('.eil_next_node')
    A.lw('t1', 0, 't1'); A.addiu('t5', 't5', -1)
    A.bgtz('t5', '.eil_node'); A.nop()
    A.label('.eil_no'); A.move('v0', 'zero'); f.ret()
    A.label('.eil_yes'); A.li('v0', 1)
    f.end()

    # Append one eligible entity to the current catalog page. a0=entity.
    f = A.func('dm_add_variant_entity', saves=['s0', 's1', 's2'])
    A.move('s0', 'a0'); call('dm_entity_variant_ifc')
    A.beqz('v0', f.epi); A.nop()
    A.lhu('t0', 0x10, 'v0'); A.beqz('t0', f.epi); A.nop()
    A.lw_abs('t0', 'dm_entities_seen'); A.addiu('t1', 't0', 1)
    A.sw_abs('t1', 'dm_entities_seen')
    A.lw_abs('t1', 'dm_entities_page'); A.sll('t1', 't1', 6)
    A.sltu('t2', 't0', 't1'); A.bnez('t2', f.epi); A.nop()
    A.subu('s1', 't0', 't1'); A.sltiu('t2', 's1', PAGE_SIZE)
    A.bnez('t2', '.ave_add'); A.nop()
    A.li('t0', 1); A.sw_abs('t0', 'dm_entities_more'); f.ret()
    A.label('.ave_add')
    A.sll('t0', 's1', 5); A.sll('t1', 's1', 4)
    A.addu('t0', 't0', 't1'); A.la('s2', 'dm_entity_names')
    A.addu('s2', 's2', 't0')
    A.addiu('a0', 's0', 0x10); call(HASH_TEXT)
    A.move('a0', 's2'); A.move('a1', 'v0'); call('dm_copy_entity_name')
    A.move('a1', 's2'); A.li('a2', D.T_SUB); call('dm_new_dyn')
    A.beqz('v0', f.epi); A.nop()
    A.sw('s0', D.E_ID, 'v0')
    A.lw('t0', D.ENTITY_HANDLE, 's0'); A.sw('t0', D.E_VALUE, 'v0')
    A.la('t0', 'p_entity_variants'); A.sw('t0', D.E_POPULATE, 'v0')
    A.la('a0', 'dm_entities_menu'); A.move('a1', 'v0'); call('dm_add_entry')
    f.end()

    f = A.func('p_entities')
    A.sw_abs('a0', 'dm_entities_entry')
    A.sw_abs('zero', 'dm_entities_page'); call('dm_populate_entities')
    f.end()
    for direction, delta in (('prev', -1), ('next', 1)):
        f = A.func('h_entities_' + direction)
        A.lw_abs('t0', 'dm_entities_page'); A.addiu('t0', 't0', delta)
        A.sw_abs('t0', 'dm_entities_page'); call('dm_populate_entities')
        f.end()

    f = A.func('dm_populate_entities', saves=['s0', 's1', 's2', 's3', 's4', 's5'])
    A.lw_abs('a0', 'dm_entities_entry'); A.la('a1', 'dm_entities_menu')
    A.la('a2', S('Entity Variants')); A.move('a3', 'zero'); call('dm_dyn_menu')
    A.la('t0', 'dm_root_menu'); A.la('t1', 'dm_entities_menu')
    A.sw('t0', D.M_PARENT, 't1')
    A.sw_abs('zero', 'dm_entities_seen'); A.sw_abs('zero', 'dm_entities_more')
    A.lw_abs('t0', G['g_world_ptr']); valid_ptr('t0', '.pe_pages')
    A.lw('s5', D.WORLD_HERO0, 't0')
    A.lw('s0', 0x78, 't0')
    A.move('a0', 's5'); call('dm_add_variant_entity')
    valid_ptr('s0', '.pe_pages')
    A.lw('s1', 0, 's0'); A.li('s4', 16384)
    A.label('.pe_node')
    A.beq('s1', 's0', '.pe_pages'); A.nop()
    valid_ptr('s1', '.pe_pages')
    A.lw('s2', 8, 's1'); A.lw('s3', 12, 's1')
    A.label('.pe_vector')
    A.beq('s2', 's3', '.pe_next_node'); A.nop()
    A.sltu('t0', 's2', 's3'); A.beqz('t0', '.pe_pages'); A.nop()
    valid_ptr('s2', '.pe_pages')
    A.lw('a0', 0, 's2'); A.beq('a0', 's5', '.pe_next_entity'); A.nop()
    call('dm_add_variant_entity')
    A.lw_abs('t0', 'dm_entities_more'); A.bnez('t0', '.pe_pages'); A.nop()
    A.label('.pe_next_entity')
    A.addiu('s2', 's2', 4); A.addiu('s4', 's4', -1)
    A.bgtz('s4', '.pe_vector'); A.nop()
    A.b('.pe_pages'); A.nop()
    A.label('.pe_next_node')
    A.lw('s1', 0, 's1'); A.addiu('s4', 's4', -1)
    A.bgtz('s4', '.pe_node'); A.nop()
    A.label('.pe_pages')
    A.lw_abs('t0', 'dm_entities_page'); A.beqz('t0', '.pe_no_prev'); A.nop()
    page_action('dm_entities_menu', 'Previous entities', 'h_entities_prev')
    A.label('.pe_no_prev')
    A.lw_abs('t0', 'dm_entities_more'); A.beqz('t0', f.epi); A.nop()
    page_action('dm_entities_menu', 'More entities', 'h_entities_next')
    f.end()

    f = A.func('p_entity_variants')
    A.sw_abs('a0', 'dm_variant_entry'); A.sw_abs('zero', 'dm_variant_page')
    call('dm_populate_variants'); f.end()
    for direction, delta in (('prev', -1), ('next', 1)):
        f = A.func('h_variants_' + direction)
        A.lw_abs('t0', 'dm_variant_page'); A.addiu('t0', 't0', delta)
        A.sw_abs('t0', 'dm_variant_page'); call('dm_populate_variants'); f.end()

    f = A.func('dm_populate_variants', saves=['s0', 's1', 's2', 's3', 's4', 's5'])
    A.la('t0', 'dm_variant_pool_desc'); A.sw('zero', 4, 't0')
    A.lw_abs('s5', 'dm_variant_entry')
    A.la('a0', 'dm_variant_menu'); A.lw('a1', D.E_NAME, 's5')
    A.move('a2', 'zero'); call('dm_menu_reset')
    # Preserve this explicit parent on page changes as well as first entry.
    A.la('t0', 'dm_entities_menu'); A.la('t1', 'dm_variant_menu')
    A.sw('t0', D.M_PARENT, 't1'); A.sw('t1', D.E_SUBMENU, 's5')
    A.lw('s0', D.E_ID, 's5'); A.move('a0', 's0'); call('dm_entity_is_loaded')
    A.beqz('v0', f.epi); A.nop()
    A.lw('t0', D.ENTITY_HANDLE, 's0'); A.lw('t1', D.E_VALUE, 's5')
    A.bne('t0', 't1', f.epi); A.nop()
    A.move('a0', 's0'); call('dm_entity_variant_ifc')
    A.beqz('v0', f.epi); A.nop()
    A.move('s0', 'v0'); A.lw('s1', 0xC, 's0'); A.lhu('s2', 0x10, 's0')
    valid_ptr('s1', f.epi)
    A.lw_abs('s3', 'dm_variant_page'); A.sll('s3', 's3', 6)
    A.sll('t0', 's3', 4); A.addu('s1', 's1', 't0'); A.move('s4', 'zero')
    A.label('.pv_loop')
    A.sltu('t0', 's3', 's2'); A.beqz('t0', '.pv_pages'); A.nop()
    A.sltiu('t0', 's4', PAGE_SIZE); A.beqz('t0', '.pv_pages'); A.nop()
    valid_ptr('s1', '.pv_pages')
    A.move('a0', 's1'); call(HASH_TEXT)
    A.sll('t0', 's4', 5); A.sll('t1', 's4', 4); A.addu('t0', 't0', 't1')
    A.la('a0', 'dm_variant_names'); A.addu('a0', 'a0', 't0')
    A.move('a1', 'v0'); call('dm_copy_entity_name')
    A.sll('t0', 's4', 5); A.sll('t1', 's4', 4); A.addu('t0', 't0', 't1')
    A.la('a1', 'dm_variant_names'); A.addu('a1', 'a1', 't0')
    A.la('a0', 'dm_variant_pool_desc'); A.li('a2', D.T_ACTION); call('dm_alloc')
    A.beqz('v0', f.epi); A.nop()
    A.sw('s1', D.E_ID, 'v0'); A.sw('s0', D.E_VALUE, 'v0')
    A.la('t0', 'h_entity_variant'); A.sw('t0', D.E_HANDLER, 'v0')
    A.la('t0', 'r_entity_variant'); A.sw('t0', D.E_RENDER, 'v0')
    A.la('a0', 'dm_variant_menu'); A.move('a1', 'v0'); call('dm_add_entry')
    A.addiu('s1', 's1', 16); A.addiu('s3', 's3', 1); A.addiu('s4', 's4', 1)
    A.b('.pv_loop'); A.nop()
    A.label('.pv_pages')
    A.lw_abs('t0', 'dm_variant_page'); A.beqz('t0', '.pv_no_prev'); A.nop()
    page_action('dm_variant_menu', 'Previous variants', 'h_variants_prev')
    A.label('.pv_no_prev')
    A.sltu('t0', 's3', 's2'); A.beqz('t0', f.epi); A.nop()
    page_action('dm_variant_menu', 'More variants', 'h_variants_next')
    f.end()

    f = A.func('h_entity_variant', saves=['s0', 's1', 's2'])
    A.move('s0', 'a0'); A.lw_abs('t0', 'dm_variant_entry')
    A.lw('s1', D.E_ID, 't0'); A.lw('s2', D.E_VALUE, 't0')
    A.move('a0', 's1'); call('dm_entity_is_loaded')
    A.beqz('v0', f.epi); A.nop()
    A.lw('t0', D.ENTITY_HANDLE, 's1'); A.bne('t0', 's2', f.epi); A.nop()
    A.lbu('t0', 0x95, 's1'); A.sltiu('t0', 't0', 2)
    A.beqz('t0', f.epi); A.nop()
    A.move('a0', 's1'); call('dm_entity_variant_ifc')
    A.lw('s1', D.E_VALUE, 's0'); A.bne('v0', 's1', f.epi); A.nop()
    A.lw('s2', D.E_ID, 's0'); A.lw('t0', 0xC, 's1')
    A.subu('t1', 's2', 't0'); A.andi('t2', 't1', 15)
    A.bnez('t2', f.epi); A.nop()
    A.lhu('t0', 0x10, 's1'); A.srl('t1', 't1', 4)
    A.sltu('t1', 't1', 't0'); A.beqz('t1', f.epi); A.nop()
    call('dm_hide')
    A.move('a0', 's1'); A.move('a1', 's2'); call(APPLY_VARIANT)
    f.end()

    # The name itself is copied, so rendering never has to dereference an entity
    # that might have disappeared while menu focus was released.
    f = A.func('r_entity_variant')
    A.move('a0', 'a1'); A.li('a1', 32); A.la('a2', S('%s'))
    A.la('a3', S('Apply')); call(G['snprintf']); f.end()

    # Script root is static; either variable scope uses the shared dynamic pool.
    for title, ptr, handler in (('Game Variables', GAME_VARS, 'p_game_vars'),
                                ('Shared Variables', SHARED_VARS, 'p_shared_vars')):
        f = A.func(handler, saves=['s0'])
        A.sw_abs('a0', 'dm_script_entry')
        A.la('t0', S(title)); A.sw_abs('t0', 'dm_script_title')
        A.li('t0', ptr); A.sw_abs('t0', 'dm_script_scope')
        A.sw_abs('zero', 'dm_script_page_number')
        call('dm_script_page')
        f.end()

    for direction, delta in (('prev', -1), ('next', 1)):
        f = A.func('h_script_' + direction)
        A.lw_abs('t0', 'dm_script_page_number'); A.addiu('t0', 't0', delta)
        A.sw_abs('t0', 'dm_script_page_number'); call('dm_script_page')
        f.end()

    f = A.func('dm_script_page')
    A.lw_abs('a0', 'dm_script_entry'); A.la('a1', 'dm_script_vars')
    A.lw_abs('a2', 'dm_script_title'); A.move('a3', 'zero'); call('dm_dyn_menu')
    A.la('t0', 'dm_script_menu'); A.la('t1', 'dm_script_vars')
    A.sw('t0', D.M_PARENT, 't1')
    A.lw_abs('t0', 'dm_script_scope'); A.lw('a0', 0, 't0')
    A.sw_abs('a0', 'dm_script_container')
    A.sw_abs('zero', 'dm_script_records'); A.sw_abs('zero', 'dm_script_count')
    call('dm_populate_script_vars')
    f.end()

    f = A.func('dm_populate_script_vars', saves=['s0', 's1', 's2', 's3', 's4', 's5'], locals_size=16)
    A.move('s0', 'a0'); valid_ptr('s0', f.epi)
    A.lw('s1', 0xC, 's0'); A.lw('s2', 0x10, 's0')
    A.sw_abs('s1', 'dm_script_records'); A.sw_abs('s2', 'dm_script_count')
    valid_ptr('s1', f.epi)
    A.sltiu('t0', 's2', 8193); A.beqz('t0', f.epi); A.nop()
    A.lw_abs('t0', 'dm_script_page_number'); A.sll('t0', 't0', 6)
    A.sltu('t1', 't0', 's2'); A.bnez('t1', '.psv_has_page'); A.nop()
    A.move('s2', 'zero'); A.b('.psv_pages'); A.nop()
    A.label('.psv_has_page')
    A.subu('s2', 's2', 't0'); A.sll('t0', 't0', 3); A.addu('s1', 's1', 't0')
    A.li('t0', PAGE_SIZE); A.sw('t0', 4, 'sp')
    A.label('.psv_loop')
    A.beqz('s2', '.psv_pages'); A.nop()
    A.lw('t0', 4, 'sp'); A.beqz('t0', '.psv_pages'); A.nop()
    A.addiu('t0', 't0', -1); A.sw('t0', 4, 'sp')
    valid_ptr('s1', '.psv_pages')
    A.lw('s3', 0, 's1'); A.lw('s4', 4, 's1')
    valid_ptr('s3', '.psv_next', aligned=False)
    valid_ptr('s4', '.psv_next')
    A.li('s5', D.T_ACTION)
    A.sw('zero', 0, 'sp')
    A.move('a0', 's0'); A.move('a1', 's3'); A.move('a2', 'sp'); call(SCRIPT_LOOKUP)
    # Never infer numeric storage from its current bit pattern.
    A.bne('v0', 's4', '.psv_next'); A.nop()
    A.lw('t0', 0, 'sp'); A.beqz('t0', '.psv_add'); A.nop()
    valid_ptr('t0', '.psv_add')
    A.lw('t1', 4, 't0'); A.li('t2', 4)
    A.bne('t1', 't2', '.psv_add'); A.nop()
    A.lw('a0', 0, 't0'); valid_ptr('a0', '.psv_add', aligned=False)
    A.la('a1', S('num')); call(G['strcasecmp'])
    A.bnez('v0', '.psv_add'); A.nop()
    # Ignore NaN/Inf numeric variables rather than introducing invalid FPU ops.
    A.lw('t0', 0, 's4'); A.li('t1', 0x7F800000); A.and_('t0', 't0', 't1')
    A.beq('t0', 't1', '.psv_add'); A.nop()
    A.li('s5', D.T_FLOATP)
    A.label('.psv_add')
    A.move('a1', 's3'); A.move('a2', 's5'); call('dm_new_dyn')
    A.beqz('v0', f.epi); A.nop()
    A.sw('s4', D.E_VALUE, 'v0')
    # Kept only for guard validation; these are values, never submenus.
    A.sw('s1', D.E_SUBMENU, 'v0')
    A.li('t0', D.T_FLOATP); A.bne('s5', 't0', '.psv_readonly'); A.nop()
    A.li_f('f0', 0.1); A.swc1('f0', D.E_ID, 'v0')
    A.li_f('f0', -1000000.0); A.swc1('f0', D.E_MIN, 'v0')
    A.li_f('f0', 1000000.0); A.swc1('f0', D.E_MAX, 'v0')
    A.b('.psv_link'); A.nop()
    A.label('.psv_readonly')
    A.la('t0', 'r_script_readonly'); A.sw('t0', D.E_RENDER, 'v0')
    A.label('.psv_link')
    A.la('a0', 'dm_script_vars'); A.move('a1', 'v0'); call('dm_add_entry')
    A.label('.psv_next')
    A.addiu('s1', 's1', 8); A.addiu('s2', 's2', -1)
    A.b('.psv_loop'); A.nop()
    A.label('.psv_pages')
    A.lw_abs('t0', 'dm_script_page_number'); A.beqz('t0', '.psv_no_prev'); A.nop()
    page_action('dm_script_vars', 'Previous variables', 'h_script_prev')
    A.label('.psv_no_prev')
    A.beqz('s2', f.epi); A.nop()
    page_action('dm_script_vars', 'More variables', 'h_script_next')
    f.end()

    f = A.func('r_script_readonly')
    A.lw('t0', D.E_VALUE, 'a0'); A.lw('a3', 0, 't0')
    A.move('a0', 'a1'); A.li('a1', 64); A.la('a2', S('0x%08x (read only)'))
    call(G['snprintf']); f.end()

    # Called before input processing and again immediately before rendering.
    # Script containers can be replaced by gameplay while START releases focus.
    f = A.func('dm_entities_guard')
    A.lw_abs('t0', 'dm_active_menu'); A.la('t1', 'dm_script_vars')
    A.bne('t0', 't1', f.epi); A.nop()
